func TestEveryReportedForeignStringIsEscaped(t *testing.T) {
	fset := token.NewFileSet()
	files := parseMissingEscapePackage(t, fset)
	for _, problem := range missingEscapeBoundaryProblems(files) {
		t.Error(problem)
	}
	findings := findMissingEscapes(fset, files)
	for _, problem := range missingEscapeInventoryProblems(findings, missingEscapeExceptions) {
		t.Error(problem)
	}
}

type missingEscapeManifestEntry struct {
	File        string `json:"file"`
	Scope       string `json:"scope"`
	Sink        string `json:"sink"`
	Provenance  string `json:"provenance"`
	Fingerprint string `json:"fingerprint"`
	Line        int    `json:"line"`
	Count       int    `json:"count"`
}

func TestMissingEscapeWriteReviewManifest(t *testing.T) {
	path := os.Getenv("MISSING_ESCAPE_MANIFEST")
	if path == "" {
		t.Skip("MISSING_ESCAPE_MANIFEST is unset")
	}
	fset := token.NewFileSet()
	files := parseMissingEscapePackage(t, fset)
	if problems := missingEscapeBoundaryProblems(files); len(problems) != 0 {
		t.Fatalf("boundary problems: %v", problems)
	}
	findings := findMissingEscapes(fset, files)
	entries := make([]missingEscapeManifestEntry, 0, len(findings))
	for _, finding := range findings {
		entries = append(entries, missingEscapeManifestEntry{
			File:        finding.file,
			Scope:       finding.scope,
			Sink:        finding.sink,
			Provenance:  finding.provenance,
			Fingerprint: finding.fingerprint,
			Line:        finding.position.Line,
			Count:       finding.count,
		})
	}
	data, err := json.MarshalIndent(entries, "", "  ")
	if err != nil {
		t.Fatalf("marshal missing-escape manifest: %v", err)
	}
	data = append(data, '\n')
	if err := os.WriteFile(path, data, 0o600); err != nil {
		t.Fatalf("write missing-escape manifest: %v", err)
	}
}
